#!/bin/sh
# ============================================================================
# sentinel_test.sh —— 第 113 次"不改硬件"的根因判定实验
# ----------------------------------------------------------------------------
# 目的: 只用 devmem + 读屏, 在没有新 bitstream 的情况下判定:
#       BIOS 显示 '4' 到底是"查表读到了 row51" 还是 "根本没走查表这条路"。
#
# 原理: 把 row20('j' 应在此) 的首字节改成一个哨兵值, 看屏幕出现什么。
#       若查表路径正常 => 屏幕显示哨兵 ⇒ 证明确实读的是 row20 ⇒ '4'另有来源
#       若屏幕仍是 '4'  ⇒ 证明**根本没读 row20** ⇒ 别在查表上继续查
#
# 关键: 用 0xEF 这种非可打印值不合适(屏幕可能显示为乱码或空格),
#       改用可打印的哨兵 'K'(0x4B) —— 它在整个 KeyCode 表里只出现在
#       row15 大写列? 需确认唯一性, 避免歧义。用 'K' 即可, 因为 row20
#       正常时是 'j'(0x6A), 改后必为 'K', 二者不会混淆。
# ============================================================================
VGA=0x080B8000
KC=0x080FFB7A      # KeyCode 表首地址(物理)

echo "=============================================================="
echo " STEP 1: 基线 —— 打印当前屏幕 + 当前 row20 内容"
echo "=============================================================="
echo "row20 @ 0x$(printf %X $((KC + 20*8))) = $(devmem $((KC + 20*8)) 8) (0x6A='j' 才是正常)"
echo ""
sh /home/workspace/vga_text_dump.sh 20 3
echo ""

echo "=============================================================="
echo " STEP 2: 写入哨兵 —— 把 row20 首字节 0x6A('j') 改成 0x4B('K')"
echo "=============================================================="
echo "原值: $(devmem $((KC + 20*8)) 8)"
devmem $((KC + 20*8)) 8 0x4B
sleep 1
echo "新值: $(devmem $((KC + 20*8)) 8)"
echo ""
echo "现在请在屏幕上按一次 j(如果映射是按扫描码的, 也可直接按物理键盘 j)"
echo ""

echo "=============================================================="
echo " STEP 3: 诊断矩阵(看完屏幕后对照)"
echo "=============================================================="
echo "  屏幕出现 'K'  => 查表路径完好, BIOS 确实读了 row20; '4' 来自别处"
echo "  屏幕出现 'j'  => 写入没生效(BIOS 用了预置 cache, 没回读 DDR)"
echo "  屏幕出现 '4'  => BIOS 根本没读 row20, 扫描码/行号源头就是错的"
echo "  屏幕啥也没有  => 这次按键没到 BIOS"
echo ""

echo "=============================================================="
echo " STEP 4: 还原 row20"
echo "=============================================================="
devmem $((KC + 20*8)) 8 0x6A
sleep 1
echo "已还原: $(devmem $((KC + 20*8)) 8) (应为 0x6a)"
