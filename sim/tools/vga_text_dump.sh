#!/bin/sh
# ============================================================================
# vga_text_dump.sh —— 从 PS 侧直接读 80186 的 VGA 文本缓冲, 打印到串口
# ----------------------------------------------------------------------------
# 为什么需要它:
#   guest(80186/DOS) 的屏幕是它自己的 DDR 里的文本缓冲, PS 看不到。而"屏幕上
#   到底出现了什么"是判断键盘问题最关键的证据 —— 只看注入器的 [exp] 行(那是
#   "我发了什么")是不够的, 必须看 "DOS 显示了什么"。
#
# 地址推导:
#   8086 实模式段 0xB800 = 文本模式显存
#   项目已实测映射: 物理 = 0x08000000 + (段<<4)   (BDA 0040:0000 读到 0x03F8=COM1 基址为证)
#   => 0x08000000 + 0xB8000 = 0x080B8000
#
# 单元格 = 2 字节: [字符, 属性]; 每行 80 单元 = 160 字节; 每字 4 字节, 一字含 2 个单元。
#
# 用法:  sh vga_text_dump.sh [起始行] [行数]     默认 0 8
# 依赖:  busybox sh + devmem(不需要 dd)
# ============================================================================
ROW_CHARS=80
BYTES_PER_ROW=$((ROW_CHARS * 2))
WORDS_PER_ROW=$((BYTES_PER_ROW / 4))
VGA_BASE=0x080B8000

START=${1:-0}
NROWS=${2:-8}

emit() {
    # $1 = 字节值; 可打印则原样输出, 否则输出 '.'
    b=$1
    if [ "$b" -ge 32 ] && [ "$b" -le 126 ]; then
        printf "\\$(printf '%03o' "$b")"
    else
        printf '.'
    fi
}

r=$START
end=$((START + NROWS))
echo "==== VGA 文本缓冲 @ 0x$(printf '%X' $VGA_BASE), 行 $START..$((end-1)) ===="
while [ "$r" -lt "$end" ]; do
    base=$((VGA_BASE + r * BYTES_PER_ROW))
    printf 'row%02d|' "$r"
    i=0
    while [ "$i" -lt "$WORDS_PER_ROW" ]; do
        w=$(devmem $((base + i * 4)) 32)
        # 低 16 位 = 单元0, 高 16 位 = 单元1; 字符在各自字节 0, 属性在字节 1
        emit $((w & 255))
        emit $(((w >> 16) & 255))
        i=$((i + 1))
    done
    echo '|'
    r=$((r + 1))
done
echo "==== 结束 ===="